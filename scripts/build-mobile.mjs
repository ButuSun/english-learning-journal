// The archived essays and study schedule live in the desktop index.html.
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';

const source = fs.readFileSync('index.html', 'utf8');
const block = source.match(/<script>\s*(const studySchedule[\s\S]*?)const keys/);
if (!block) throw Error('Archived data block was not found; refusing to overwrite mobile data.');
const context = vm.createContext({});
vm.runInContext(block[1] + ';globalThis.output={records,studySchedule}', context, {timeout: 1000});

fs.writeFileSync('mobile/data.json', JSON.stringify(context.output, null, 2) + '\n');

// The installed Android app downloads a fixed set of four files. Include the
// shared review source in those assets so old installs can update in place.
for (const [file, extension] of [['app.js', 'js'], ['style.css', 'css']]) {
  const shared = fs.readFileSync('shared/grammar-review.' + extension, 'utf8');
  const mobile = fs.readFileSync('src/mobile/' + file, 'utf8');
  const parts = extension === 'js' ? [shared, mobile] : [mobile, shared];
  fs.writeFileSync('mobile/' + file, '/* Generated by scripts/build-mobile.mjs. */\n' + parts.join('\n'));
}

const files = Object.fromEntries(['index.html', 'app.js', 'style.css', 'data.json'].map(name =>
  [name, crypto.createHash('sha256').update(fs.readFileSync('mobile/' + name)).digest('hex')]
));
const bundle = crypto.createHash('sha256').update(JSON.stringify(files)).digest('hex');
fs.writeFileSync('mobile/version.json', JSON.stringify({
  version: '1.0.0', bundle, minNativeVersion: 1, apkVersionCode: 1, apkUrl: '', files
}, null, 2) + '\n');
console.log('Mobile data and verified update manifest generated.');
